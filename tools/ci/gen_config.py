#!/usr/bin/env python3
"""Generate config/settings.yaml: every setting the agent reads, its variable, default and meaning.

    python tools/ci/gen_config.py          # rewrite config/settings.yaml
    python tools/ci/gen_config.py --check  # exit 1 if it is stale or .env.example misses a variable

Sources of truth: field defaults in src/podcast_agent/config.py and the comments in .env.example.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "src" / "podcast_agent" / "config.py"
ENV_EXAMPLE = ROOT / ".env.example"
OUT = ROOT / "config" / "settings.yaml"
FIELD = re.compile(r"^\s{4}(\w+): [^=]+= field\(default_factory=lambda: _env\w*\(\"([A-Z0-9_]+)\"", re.M)
# Variables read outside Settings (standard OpenTelemetry ones are documented in docs/OBSERVABILITY.md).
EXTRA = {"AWS_DEFAULT_REGION"}


def env_docs() -> tuple[dict[str, str], list[str]]:
    docs: dict[str, str] = {}
    keys: list[str] = []
    pending: list[str] = []
    for line in ENV_EXAMPLE.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("# ---"):
            pending = []
        elif stripped.startswith("#") and "=" not in stripped.split()[1:2][0:1]:
            pending.append(stripped.lstrip("# ").strip())
        m = re.match(r"^#?\s*([A-Z][A-Z0-9_]+)=", stripped)
        if m and not stripped.startswith("# ---"):
            key = m.group(1)
            keys.append(key)
            docs[key] = " ".join(p for p in pending if p and not re.match(r"^[A-Z0-9_]+=", p))
            pending = []
        elif not stripped:
            pending = []
    return docs, keys


def render() -> tuple[str, list[str]]:
    sys.path.insert(0, str(ROOT / "src"))
    fields = FIELD.findall(CONFIG.read_text(encoding="utf-8"))
    saved = {k: os.environ.pop(k) for k in [env for _, env in fields] if k in os.environ}
    try:
        from podcast_agent.config import Settings

        defaults = Settings()
    finally:
        os.environ.update(saved)
    docs, keys = env_docs()
    missing = [env for _, env in fields if env not in keys]
    lines = ["# Generated by tools/ci/gen_config.py from src/podcast_agent/config.py and .env.example. Do not edit.",
             "# Every setting the agent reads: the environment variable, the Settings field, its default and meaning.",
             "settings:"]
    for name, env in fields:
        value = getattr(defaults, name)
        if name == "today":
            value = "<today's date>"
        shown = "null" if value is None else (str(value).lower() if isinstance(value, bool) else str(value))
        lines += [f"  - env: {env}", f"    field: {name}", f'    default: "{shown}"']
        if docs.get(env):
            lines.append(f'    help: "{docs[env].replace(chr(34), chr(39))}"')
    return "\n".join(lines) + "\n", missing


def main() -> int:
    text, missing = render()
    if missing:
        print(f".env.example is missing: {', '.join(missing)}")
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        if stale:
            print("config/settings.yaml is stale: run `make config`")
        return 1 if (stale or missing) else 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
